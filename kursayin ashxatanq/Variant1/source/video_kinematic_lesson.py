SCENES = []


def add(id, chapter, view, stage, title, speech, note, formula='', focus=(), i=2, sheet=None):
    scene = dict(id=id, chapter=chapter, view=view, stage=stage, i=i,
                 title=title, speech=speech, note=note, formula=formula, focus=list(focus))
    if sheet is not None:
        scene['sheet'] = sheet
    assert len(formula) <= 80, (id, len(formula))
    SCENES.append(scene)


