def pv_area(f, a, b, lab1='1', lab2='2', mark=True, xl='υ', yl='p', extra=''):
    """Process curve from u=a to u=b with the area under it (work) shaded."""
    pts = _pts(f, a, b)
    area = _path(pts) + f' L{_x(b):.1f},{Y0} L{_x(a):.1f},{Y0} Z'
    marks = (f'<path d="M{_x(a):.1f},{_y(f(a)):.1f} V{Y0} M{_x(b):.1f},{_y(f(b)):.1f} V{Y0}" class="dash"/>'
             f'<text x="{_x(a)-6:.1f}" y="{Y0+13}">υ₁</text><text x="{_x(b)-6:.1f}" y="{Y0+13}">υ₂</text>') if mark else ''
    return _svg(_axes(xl, yl) + f'<path d="{area}" class="area"/>' + marks + f'<path d="{_path(pts)}" class="cv"/>'
                + _dot(a, f(a), lab1) + _dot(b, f(b), lab2) + extra)

def pv_tech(f, a, b):
    """Expansion curve 1-2 with the area between it and the p axis shaded (∫υdp)."""
    pts = _pts(f, a, b)
    area = _path(pts) + f' L{X0},{_y(f(b)):.1f} L{X0},{_y(f(a)):.1f} Z'
    return _svg(_axes() + f'<path d="{area}" class="area"/>'
                + f'<path d="M{X0},{_y(f(a)):.1f} H{_x(a):.1f} M{X0},{_y(f(b)):.1f} H{_x(b):.1f}" class="dash"/>'
                + f'<text x="{X0-22}" y="{_y(f(a))+4:.1f}">p₁</text><text x="{X0-22}" y="{_y(f(b))+4:.1f}">p₂</text>'
                + f'<path d="{_path(pts)}" class="cv"/>' + _dot(a, f(a), '1') + _dot(b, f(b), '2'))

