def gdf_plot():
    k = 1.4
    lm = ((k + 1) / (k - 1)) ** .5
    tau = lambda l: 1 - (k - 1) / (k + 1) * l * l
    curves = [(lambda l: tau(l), 'τ'), (lambda l: tau(l) ** (k / (k - 1)), 'π'),
              (lambda l: tau(l) ** (1 / (k - 1)), 'ε'),
              (lambda l: l * ((k + 1) / 2) ** (1 / (k - 1)) * tau(l) ** (1 / (k - 1)), 'q')]
    sx = lambda l: l / 2.5
    body = _axes('λ', '')
    for j, (f, lab) in enumerate(curves):
        pts = [(sx(u), f(u)) for u in [lm * i / 60 for i in range(61)]]
        lu = {0: 1.75, 1: 1.25, 2: 1.5, 3: .62}[j]
        body += f'<path d="{_path(pts)}" class="cv c{j}"/><text x="{_x(sx(lu))+4:.1f}" y="{_y(f(lu))-4:.1f}">{lab}</text>'
    body += (f'<path d="M{_x(sx(1)):.1f},{Y1} V{Y0}" class="dash"/><text x="{_x(sx(1))-4:.1f}" y="{Y0+13}">1</text>'
             f'<text x="{_x(sx(lm))-8:.1f}" y="{Y0+13}">λₘₐₓ</text><text x="{X0-14}" y="{_y(1)+4:.1f}">1</text>')
    return _svg(body)

